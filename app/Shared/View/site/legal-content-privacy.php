<h2>1. Introdução</h2>
<p>
  Esta Política de Privacidade descreve como coletamos, usamos, armazenamos e protegemos
  os dados pessoais de visitantes e clientes que utilizam nosso site e serviços de pedido online.
  O tratamento de dados observa a Lei Geral de Proteção de Dados Pessoais (Lei nº 13.709/2018 — LGPD)
  e demais normas aplicáveis.
</p>

