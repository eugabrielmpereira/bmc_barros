<h2>3. Dados que coletamos</h2>
<p>Podemos coletar, conforme o uso do site:</p>
<ul>
  <li><strong>Cadastro e checkout:</strong> nome, CPF/CNPJ, e-mail, telefone, endereço de entrega e observações do pedido.</li>
  <li><strong>Conta do cliente:</strong> credenciais de acesso (senha armazenada de forma criptografada), histórico de pedidos e endereços salvos.</li>
  <li><strong>Navegação:</strong> endereço IP, data e hora de acesso, páginas visitadas, identificadores de sessão e cookies essenciais ao funcionamento do carrinho e login.</li>
  <li><strong>Comunicação:</strong> mensagens enviadas por formulários ou canais de atendimento.</li>
  <li><strong>Aviso de estoque:</strong> e-mail informado quando disponível o recurso de notificação de produto.</li>
</ul>

<h2>4. Finalidades do tratamento</h2>
<p>Utilizamos os dados para:</p>
<ul>
  <li>Processar pedidos, reservar estoque, confirmar valores e condições comerciais.</li>
  <li>Emitir cobranças (ex.: Pix) e registrar pagamentos via parceiros de pagamento.</li>
  <li>Entregar produtos ou organizar retirada na loja.</li>
  <li>Autenticar usuários, prevenir fraudes e cumprir obrigações legais.</li>
  <li>Enviar comunicações sobre pedidos (confirmação, status, contato comercial).</li>
  <li>Melhorar a experiência no site e cumprir exigências fiscais e regulatórias.</li>
</ul>

